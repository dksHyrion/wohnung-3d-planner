export function getCatalogItemName(
  tpl: { name: string },
  lang?: Language
): string {
  const activeLang = lang ?? getGlobalLanguage();
  if (activeLang === 'en' && CATALOG_ITEM_TRANSLATIONS_EN[tpl.name]) {
    return CATALOG_ITEM_TRANSLATIONS_EN[tpl.name];
  }
  return tpl.name;
}


